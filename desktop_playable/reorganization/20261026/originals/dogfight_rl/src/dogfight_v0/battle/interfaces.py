from typing import Protocol, runtime_checkable

from dogfight_v0.agents.agent_interface import AgentInterface
from dogfight_v0.battle.types import BattleAction, BattleObservation, IntelRecord, ShotResult, VisibilityResult


@runtime_checkable
class IntelServiceInterface(Protocol):
    def reset(self, start_time_s: float = 0.0) -> None: ...
    def update(self, current_time_s: float, agents: dict[str, AgentInterface]) -> bool: ...
    def get_last_known_position(self, requester_id: str, target_id: str) -> IntelRecord | None: ...
    def get_snapshot_for(self, requester_id: str) -> dict[str, IntelRecord]: ...


@runtime_checkable
class VisibilityServiceInterface(Protocol):
    def observe_target(self, observer: AgentInterface, target: AgentInterface) -> VisibilityResult: ...
    def observe_all(self, observer: AgentInterface, candidates: list[AgentInterface]) -> list[VisibilityResult]: ...


@runtime_checkable
class WeaponServiceInterface(Protocol):
    def can_fire(self, shooter_id: str, current_time_s: float) -> bool: ...
    def fire(self, shooter: AgentInterface, agents: dict[str, AgentInterface], current_time_s: float) -> ShotResult: ...
    def reset(self) -> None: ...


@runtime_checkable
class HealthSystemInterface(Protocol):
    def reset(self, agent_ids: list[str]) -> None: ...
    def get_health(self, agent_id: str) -> float: ...
    def is_alive(self, agent_id: str) -> bool: ...
    def apply_damage(self, target_id: str, amount: float, source_id: str | None = None) -> float: ...
    def kill(self, agent_id: str) -> None: ...


@runtime_checkable
class BattleManagerInterface(Protocol):
    def reset(self, seed: int | None = None) -> None: ...
    def start_round(self) -> None: ...
    def step(self, dt: float) -> None: ...
    def is_round_over(self) -> bool: ...
    def get_alive_agents(self) -> list[str]: ...
    def get_winner(self) -> str | None: ...
    def get_match_state(self) -> dict: ...


@runtime_checkable
class BattlePolicyInterface(Protocol):
    def reset(self) -> None: ...
    def act(self, observation: BattleObservation) -> BattleAction: ...

